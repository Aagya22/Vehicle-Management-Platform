async function seedVehicles() {
    try {
        await dataSource.initialize();

        console.log('Database connected successfully.');

        const vehicleRepository = dataSource.getRepository(Vehicle);

        // Get existing vehicle codes.
        const existingVehicles = await vehicleRepository.find({
            select: {
                vehicleCode: true,
            },
        });

        const existingCodes = new Set(
            existingVehicles.map((vehicle) => vehicle.vehicleCode),
        );

        // Only insert vehicles that do not already exist.
        const newVehicles = vehicles.filter(
            (vehicle) => !existingCodes.has(vehicle.vehicleCode!),
        );

        if (newVehicles.length === 0) {
            console.log('All seed vehicles already exist.');
            return;
        }

        await vehicleRepository.insert(newVehicles);

        console.log(
            `Successfully seeded ${newVehicles.length} vehicles.`,
        );
    } catch (error) {
        console.error('Error seeding vehicles:', error);
        process.exitCode = 1;
    } finally {
        if (dataSource.isInitialized) {
            await dataSource.destroy();
        }
    }
}

seedVehicles();